CREATE TABLE Customer_Master (
    Customer_ID VARCHAR(10) PRIMARY KEY,
    Customer_Name VARCHAR(100),
    Gender VARCHAR(10),
    DOB DATE ,
    Age INT,
    Email VARCHAR(100),
    Phone VARCHAR(15),
    City VARCHAR(50),
    State VARCHAR(50),
    Region VARCHAR(20),
    Join_Date DATE,
    Customer_Segment VARCHAR(20)
);